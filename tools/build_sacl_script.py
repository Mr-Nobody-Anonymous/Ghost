#!/usr/bin/env python3
"""Generate the SACL script that makes 4663-based rules able to fire (G-08).

Three rules read `ObjectName` from Security 4663 - a registry or file *read*.
Sysmon cannot log that: it records create, write, delete, and process access,
never "this process opened this object for reading". Windows 4663 exists only
when an object carries a SACL with an Audit ACE, and a SACL is set per object.

`telemetry/auditpol.md` said "use Set-Acl / subinacl / your EDR's tooling to add
an Audit Read ACE". That is three options and no command, for a step that has to
be exact or the rule never fires and never says why. This emits the exact
commands, derived from the paths the rules actually read, plus the backup and
rollback the manual never mentioned.

Usage:
    python3 tools/build_sacl_script.py              # write deploy/telemetry/
    python3 tools/build_sacl_script.py --check      # fail when stale
"""
import argparse
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "deploy" / "telemetry"
TEMPLATE = OUT / "set-sacls.ps1"

# The paths that carry a 4663 rule, derived from the rules themselves.
#
# This list used to be written by hand and contained four targets, two of which
# served no rule at all: `credential_file_access.yml` reads Sysmon 11 (file
# create), not 4663, and `patch_sequence.yml` mentions 4663 only in a comment
# explaining why it does not use it. A SACL on `C:\Users` would have produced
# millions of events a day to feed a rule that was never listening.
#
# So: the hint is declared per rule, and `--check` fails when a rule that reads
# 4663 has no hint, or when a hint names a rule that does not read it.
SACL_HINTS = {
    "cpu_info_read": {
        "path": "HKLM\\HARDWARE\\DESCRIPTION\\System\\CentralProcessor\\0",
        "why": "The rule matches AccessMask 0x1 (read) on this key. Without a "
               "SACL the read is never logged, so the rule cannot fire.",
    },
}


SCRIPT = r'''<#
.SYNOPSIS
    Apply the SACLs that Security 4663 rules depend on.

.DESCRIPTION
    Generated by tools/build_sacl_script.py. Do not hand-edit: regenerate.

    Three rules in this repository read ObjectName from Security event 4663.
    That event does not exist unless an object carries a SACL with an Audit
    ACE, and Sysmon cannot produce it - Sysmon logs create, write and delete,
    not read. Without this script those rules are not "quiet", they are
    incapable of firing, and nothing in the telemetry says so.

    Every command is `auditpol` for the subcategory and `Set-Acl` for the
    object. Run as Administrator on the lab host, then capture 24 hours of
    baseline before trusting the volume.

.PARAMETER Rollback
    Restore the saved ACLs and stop auditing. Run this before deleting the VM,
    so the next operator inherits a known state rather than a half-applied one.

.EXAMPLE
    .\set-sacls.ps1
    .\set-sacls.ps1 -Rollback
#>
[CmdletBinding()]
param(
    [switch]$Rollback,
    [string]$BackupDir = "$env:ProgramData\ghost-lab\sacl-backup"
)

$ErrorActionPreference = 'Stop'
$principal = New-Object System.Security.Principal.NTAccount("Everyone")
$rights = [System.Security.AccessControl.RegistryRights]::ReadKey
# AuditRule, not AuditRule with InheritOnly: the reads this lab cares about are
# on these exact objects, and inheritance turns a 300-event/day SACL into a
# 300,000-event/day one.
$inheritance = [System.Security.AccessControl.InheritanceFlags]::None
$propagation = [System.Security.AccessControl.PropagationFlags]::None
$auditType = [System.Security.AccessControl.AuditFlags]::Success

$targets = @(
__TARGETS__
)

function Get-ObjectAclPath {
    param([string]$Path)
    if ($Path -like 'HK*') { return $null }   # registry: handled by name
    return $Path
}

if ($Rollback) {
    foreach ($t in $targets) {
        $safe = ($t.Path -replace '[\\:]', '_')
        $bak = Join-Path $BackupDir "$safe.acl"
        if ($t.Path -like 'HK*') {
            if (Test-Path $bak) {
                & icacls $t.Path /restore $bak | Out-Null
                Write-Host "restored registry ACL: $($t.Path)"
            }
        } elseif (Test-Path $bak) {
            & icacls $t.Path /restore $bak | Out-Null
            Write-Host "restored file ACL: $($t.Path)"
        }
    }
    & auditpol /set /subcategory:"Registry Object" /success:disable /failure:disable
    & auditpol /set /subcategory:"File System Object" /success:disable /failure:disable
    Write-Host "auditing disabled. The 4663 rules will go quiet - that is the point."
    exit 0
}

# 1. The subcategory has to be on before any SACL produces an event.
& auditpol /set /subcategory:"Registry Object" /success:enable /failure:enable
& auditpol /set /subcategory:"File System Object" /success:enable /failure:enable

New-Item -ItemType Directory -Force -Path $BackupDir | Out-Null

foreach ($t in $targets) {
    if (-not (Test-Path $t.Path) -and $t.Path -notlike 'HK*') {
        Write-Warning "absent on this host, skipping: $($t.Path)"
        continue
    }
    $safe = ($t.Path -replace '[\\:]', '_')
    $bak = Join-Path $BackupDir "$safe.acl"
    if (-not (Test-Path $bak)) {
        & icacls $t.Path /save $bak | Out-Null
        Write-Host "backed up ACL: $($t.Path) -> $bak"
    }

    if ($t.Path -like 'HK*') {
        $key = [Microsoft.Win32.Registry]::LocalMachine.OpenSubKey(
            ($t.Path -replace '^HKLM\\', ''),
            [Microsoft.Win32.RegistryKeyPermissionCheck]::ReadWriteSubTree,
            [System.Security.AccessControl.RegistryRights]::ChangePermissions)
        $acl = $key.GetAccessControl()
        $rule = New-Object System.Security.AccessControl.RegistryAuditRule(
            $principal, $rights, $inheritance, $propagation, $auditType)
        $acl.AddAuditRule($rule)
        $key.SetAccessControl($acl)
        $key.Close()
        Write-Host "audit ACE added: $($t.Path) - $($t.Why)"
    } else {
        $acl = Get-Acl -Path $t.Path
        $rule = New-Object System.Security.AccessControl.FileSystemAuditRule(
            $principal,
            [System.Security.AccessControl.FileSystemRights]::ReadData,
            $inheritance, $propagation, $auditType)
        $acl.AddAuditRule($rule)
        Set-Acl -Path $t.Path -AclObject $acl
        Write-Host "audit ACE added: $($t.Path) - $($t.Why)"
    }
}

Write-Host ""
Write-Host "Applied. Now capture 24 hours of clean baseline before enabling the"
Write-Host "rules that read 4663, or the volume will bury the signal."
Write-Host "Rollback: .\set-sacls.ps1 -Rollback"

# Prove the SACL is live. A SACL that reads back empty is the failure this
# script exists to prevent, and it looks exactly like a quiet rule.
foreach ($t in $targets) {
    if ($t.Path -like 'HK*') {
        $key = [Microsoft.Win32.Registry]::LocalMachine.OpenSubKey(
            ($t.Path -replace '^HKLM\\', ''))
        $has = ($key.GetAccessControl().GetAuditRules(
            $true, $true, [System.Security.Principal.NTAccount]) | Measure-Object).Count
        $key.Close()
    } else {
        $has = (Get-Acl -Path $t.Path -Audit).Audit.Count
    }
    if ($has -lt 1) {
        Write-Error "SACL read back empty for $($t.Path) - the rule that reads it cannot fire"
    }
}
Write-Host "verified: every target reports at least one audit ACE."
'''


def ps_list(items):
    out = []
    for path, (rules, why) in items.items():
        escaped = path.replace("'", "''")
        why_escaped = why.replace("'", "''")
        out.append("    [pscustomobject]@{ Path = '%s'; Rules = '%s'; Why = '%s' }"
                   % (escaped, rules, why_escaped))
    return "\n".join(out)


def ps_list_for(hints):
    out = []
    for rule, spec in hints.items():
        out.append("    [pscustomobject]@{ Path = '%s'; Rules = '%s'; Why = '%s' }"
                   % (spec["path"].replace("'", "''"), rule,
                      spec["why"].replace("'", "''")))
    return "\n".join(out)


def rules_reading_objectname():
    """Which rules actually read a 4663-only field.

    The first version substring-matched the description and the whole
    `detection` blob, so it flagged two rules that only *mention* 4663 -
    one explaining in prose why the pairing cannot work, one in a UUID. A
    detector that counts prose as a data dependency generates SACLs for rules
    that are not listening.
    """
    import yaml
    found = []
    for path in sorted((ROOT / "sigma").rglob("*.yml")):
        doc = yaml.safe_load(path.read_text(encoding="utf-8"))
        if not isinstance(doc, dict):
            continue
        reads = False
        for name, body in (doc.get("detection") or {}).items():
            if name == "condition" or not isinstance(body, dict):
                continue
            for key, value in body.items():
                field = key.split("|", 1)[0]
                if field == "ObjectName":
                    reads = True
                if field == "EventID" and 4663 in (
                        value if isinstance(value, list) else [value]):
                    reads = True
        if reads:
            found.append(path.stem)
    return found


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    unlisted = sorted(set(rules_reading_objectname()) - set(SACL_HINTS))
    if unlisted:
        for rule in unlisted:
            print(f"FAIL {rule} reads a 4663 field and no SACL targets the "
                  f"path it reads - the rule cannot fire", file=sys.stderr)
        return 1

    text = SCRIPT.replace("__TARGETS__", ps_list_for(SACL_HINTS))
    if args.check:
        if not TEMPLATE.is_file() or TEMPLATE.read_text(encoding="utf-8") != text:
            print("FAIL deploy/telemetry/set-sacls.ps1 is stale; run "
                  "python3 tools/build_sacl_script.py", file=sys.stderr)
            return 1
        print(f"sacl: {len(SACL_HINTS)} target(s), every 4663 rule covered")
        return 0

    OUT.mkdir(parents=True, exist_ok=True)
    TEMPLATE.write_text(text, encoding="utf-8")
    print(f"sacl: wrote {TEMPLATE.relative_to(ROOT)} for {len(SACL_HINTS)} target(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
