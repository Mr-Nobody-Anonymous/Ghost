#!/usr/bin/env python3
"""Emit each platform's field-alias configuration from one map.

`docs/deployment.md` gave the Splunk `props.conf` snippet and said, in the gap
register's own words, that "Elastic/Kusto equivalents are not written". So a
Splunk user got three working alias lines and an Elastic user got nothing.

`telemetry/field-map.json` is the single source: canonical Sigma field ->
Splunk / Elastic / Kusto name, with a note wherever the mapping is not a clean
rename. This tool writes the three configs from it and proves they cover every
field the rules actually read.

Config shapes differ because the platforms do:

  * Splunk: `FIELDALIAS-<name> = <src> AS <dest>` in props.conf
  * Elastic: a component template setting `properties.<ecs field>` - but Elastic
    does not rename fields at query time the way Splunk does, so what it actually
    needs is a **runtime field or ingest pipeline** that adds the canonical name.
    Written here as a pipeline `set`/`rename` stage list.
  * Kusto: a table update policy or a `datatable` view; written as a
    `let Sigma = (...) => ...` view per log table, which is the only shape that
    does not require changing the workspace schema.

`pipeline/field_contract.py` already checks that every field a rule reads is
documented in telemetry/data-sources.md. This adds the other half: every
documented field has a name on every platform, so "the rule fires everywhere" is
a configuration fact rather than an assumption.

Usage:
    python3 pipeline/build_field_map.py            # write deploy/fieldmap/
    python3 pipeline/build_field_map.py --check    # fail if stale or incomplete
"""
import argparse
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
MAP = ROOT / "telemetry" / "field-map.json"
OUT = ROOT / "deploy" / "fieldmap"
PLATFORMS = ("splunk", "elastic", "kusto")

# Characters Splunk will not accept in an alias name.
SPLUNK_UNSAFE = re.compile(r"[^A-Za-z0-9_]")


def load_map():
    return json.loads(MAP.read_text(encoding="utf-8"))


def rule_fields():
    """Every canonical field a rule reads, from the detection blocks."""
    import yaml
    fields = set()
    for path in sorted((ROOT / "sigma").rglob("*.yml")):
        doc = yaml.safe_load(path.read_text(encoding="utf-8"))
        if not isinstance(doc, dict):
            continue
        for name, body in (doc.get("detection") or {}).items():
            if name == "condition" or not isinstance(body, dict):
                continue
            for key in body:
                fields.add(key.split("|", 1)[0])
    return fields


def splunk_alias(field, meta):
    dest = meta["splunk"]
    alias = "sigma_" + SPLUNK_UNSAFE.sub("_", field)
    if dest == field:
        return f"# {field}: already the native name, no alias needed", None
    return f"FIELDALIAS-{alias} = {dest} AS {field}", dest


def build_splunk(fields, data):
    """One stanza per sourcetype, driven by `sourcetypes` in the map.

    A field belongs to a sourcetype, not to a platform: a proxy header alias in
    the Sysmon stanza is a config that parses and never matches, which is worse
    than no config because it looks done.
    """
    derived = data.get("derived", {})
    lines = [
        "# Splunk field aliases, generated by pipeline/build_field_map.py.",
        "#",
        "# Apply on the indexer or the heavy forwarder. Do not hand-edit:",
        "# regenerate from telemetry/field-map.json.",
        "#",
        "# The alias direction matters: `EventCode AS EventID` adds the canonical",
        "# name without removing the platform's. A rule using EventID then works",
        "# and a dashboard using EventCode keeps working.",
    ]
    for sourcetype, wanted in data["sourcetypes"].items():
        lines += ["", f"[{sourcetype}]"]
        body = []
        for field in wanted:
            if field not in fields:
                continue  # no rule reads it; emitting it implies a rule does
            if field in derived:
                lines.append(derived[field]["splunk"].replace(
                    "eval ", "EVAL-sigma_", 1).replace(" = ", " = ", 1))
                continue
            meta = data["fields"].get(field)
            if meta is None:
                continue
            dest = meta["splunk"]
            if dest == field:
                continue  # native
            alias = "sigma_" + SPLUNK_UNSAFE.sub("_", field)
            body.append(f"FIELDALIAS-{alias} = {dest} AS {field}")
        native = [f for f in wanted if f in fields and f in data["fields"]
                  and f not in derived and data["fields"][f]["splunk"] == f]
        if body:
            lines += body
        else:
            lines.append("# (no aliases needed)")
        if native:
            lines.append("# already native under this name: " + ", ".join(native))
    unused = sorted(set(data["fields"]) - fields)
    if unused:
        lines += ["", "# Declared in the map but read by no rule yet: "
                  + ", ".join(unused)]
    return "\n".join(lines) + "\n"


def build_elastic(fields, data):
    """An ingest pipeline: rename where the ECS name is the only one, set where
    the platform name has no ECS home."""
    pipeline = []
    for field in sorted(fields):
        meta = data["fields"].get(field)
        if meta is None:
            continue
        ecs = meta["elastic"]
        if ecs == field:
            continue
        pipeline.append({
            "set": {
                "field": field,
                # Elastic mustache. Plain concatenation: .format() treats the
                # doubled braces as an escape and silently emits {ecs}.
                "value": "{{" + ecs + "}}",
                "if": f"ctx.{ecs} != null",
                "description": f"canonical alias for {ecs}",
                "ignore_failure": True,
            }
        })
        if ecs.count(".") >= 2 and "winlog.event_data" not in ecs:
            continue  # present in this deployment's template already
    doc = {
        "_meta": {
            "description": "Elasticsearch ingest pipeline adding the canonical "
                           "field names the rules read.",
            "generated_by": "pipeline/build_field_map.py",
            "install": "PUT _ingest/pipeline/sigma-canonical",
            "attach_to": "the Sysmon / Windows integration data stream",
            "warning": "Not executed against a live cluster. `set` with a "
                       "mustache reference is the documented form; confirm the "
                       "field resolves in your ECS version before enabling.",
        },
        "processors": pipeline,
    }
    return json.dumps(doc, indent=2) + "\n"


def build_kusto(fields, data):
    lines = [
        "// Kusto canonical-field views, generated by pipeline/build_field_map.py.",
        "//",
        "// The rules read Sigma names; these functions expose each log table under",
        "// those names without changing the workspace schema. Attach them to the",
        "// queries, not to the tables: a stored function is the only shape that does",
        "// not require a schema migration.",
        "//",
        "// Not executed against a live workspace.",
        "",
    ]
    by_table = {
        "SecurityEvent": ("EventID", "Computer", "ObjectName", "AccessMask"),
        "DeviceProcessEvents": ("Image", "CommandLine", "ParentImage",
                                "ProcessId", "ProcessGuid"),
        "Sysmon": ("Image", "CommandLine", "ParentImage", "TargetFilename",
                   "TargetObject", "ProcessGuid", "ParentProcessGuid"),
    }
    for table, wanted in by_table.items():
        projections = []
        for field in wanted:
            meta = data["fields"].get(field)
            if meta is None:
                continue
            native = meta["kusto"]
            projections.append(
                f"{field} = {native}" if native != field
                else f"{field} = {field}")
        lines.append(f"let Sigma_{table} = {table} | project "
                     + ", ".join(projections) + ";")
    lines.append("")
    lines.append("// Fields with no clean Kusto equivalent are listed in")
    lines.append("// telemetry/field-map.json under `note`; read them before")
    lines.append("// assuming a rule behaves the same on Sentinel as on Splunk.")
    return "\n".join(lines) + "\n"


BUILDERS = {"splunk": ("props-sigma.conf", build_splunk),
            "elastic": ("ingest-pipeline.json", build_elastic),
            "kusto": ("sigma-views.kql", build_kusto)}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()

    data = load_map()
    declared = set(data["fields"])
    used = rule_fields()
    missing = sorted(used - declared)
    if missing:
        for field in missing:
            print(f"FAIL {field}: a rule reads it and telemetry/field-map.json "
                  f"does not name it on any platform", file=sys.stderr)
        return 1
    for field, meta in data["fields"].items():
        for platform in PLATFORMS:
            if platform not in meta:
                print(f"FAIL {field}: no {platform} mapping", file=sys.stderr)
                return 1

    stale = []
    for platform, (name, builder) in BUILDERS.items():
        text = builder(used, data)
        target = OUT / name
        if args.check:
            if not target.is_file() or target.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding="utf-8")

    if args.check:
        if stale:
            for name in stale:
                print(f"FAIL deploy/fieldmap/{name} is stale; run "
                      f"python3 pipeline/build_field_map.py", file=sys.stderr)
            return 1
        print(f"field map: {len(used)} fields a rule reads, all named on "
              f"{len(PLATFORMS)} platforms; {len(BUILDERS)} config(s) current")
        return 0

    print(f"field map: wrote {len(BUILDERS)} config(s) to deploy/fieldmap/ "
          f"for {len(used)} fields across {len(PLATFORMS)} platforms")
    return 0


if __name__ == "__main__":
    sys.exit(main())
