<#
.SYNOPSIS
    Apply the SACLs that Security 4663 rules depend on.

.DESCRIPTION
    Generated by tools/build_sacl_script.py. Do not hand-edit: regenerate.

    Three rules in this repository read ObjectName from Security event 4663.
    That event does not exist unless an object carries a SACL with an Audit
    ACE, and Sysmon cannot produce it - Sysmon logs create, write and delete,
    not read. Without this script those rules are not "quiet", they are
    incapable of firing, and nothing in the telemetry says so.

    Every command is `auditpol` for the subcategory and `Set-Acl` for the
    object. Run as Administrator on the lab host, then capture 24 hours of
    baseline before trusting the volume.

.PARAMETER Rollback
    Restore the saved ACLs and stop auditing. Run this before deleting the VM,
    so the next operator inherits a known state rather than a half-applied one.

.EXAMPLE
    .\set-sacls.ps1
    .\set-sacls.ps1 -Rollback
#>
[CmdletBinding()]
param(
    [switch]$Rollback,
    [string]$BackupDir = "$env:ProgramData\ghost-lab\sacl-backup"
)

$ErrorActionPreference = 'Stop'
$principal = New-Object System.Security.Principal.NTAccount("Everyone")
$rights = [System.Security.AccessControl.RegistryRights]::ReadKey
# AuditRule, not AuditRule with InheritOnly: the reads this lab cares about are
# on these exact objects, and inheritance turns a 300-event/day SACL into a
# 300,000-event/day one.
$inheritance = [System.Security.AccessControl.InheritanceFlags]::None
$propagation = [System.Security.AccessControl.PropagationFlags]::None
$auditType = [System.Security.AccessControl.AuditFlags]::Success

$targets = @(
    [pscustomobject]@{ Path = 'HKLM\HARDWARE\DESCRIPTION\System\CentralProcessor\0'; Rules = 'cpu_info_read'; Why = 'The rule matches AccessMask 0x1 (read) on this key. Without a SACL the read is never logged, so the rule cannot fire.' }
)

function Get-ObjectAclPath {
    param([string]$Path)
    if ($Path -like 'HK*') { return $null }   # registry: handled by name
    return $Path
}

if ($Rollback) {
    foreach ($t in $targets) {
        $safe = ($t.Path -replace '[\\:]', '_')
        $bak = Join-Path $BackupDir "$safe.acl"
        if ($t.Path -like 'HK*') {
            if (Test-Path $bak) {
                & icacls $t.Path /restore $bak | Out-Null
                Write-Host "restored registry ACL: $($t.Path)"
            }
        } elseif (Test-Path $bak) {
            & icacls $t.Path /restore $bak | Out-Null
            Write-Host "restored file ACL: $($t.Path)"
        }
    }
    & auditpol /set /subcategory:"Registry Object" /success:disable /failure:disable
    & auditpol /set /subcategory:"File System Object" /success:disable /failure:disable
    Write-Host "auditing disabled. The 4663 rules will go quiet - that is the point."
    exit 0
}

# 1. The subcategory has to be on before any SACL produces an event.
& auditpol /set /subcategory:"Registry Object" /success:enable /failure:enable
& auditpol /set /subcategory:"File System Object" /success:enable /failure:enable

New-Item -ItemType Directory -Force -Path $BackupDir | Out-Null

foreach ($t in $targets) {
    if (-not (Test-Path $t.Path) -and $t.Path -notlike 'HK*') {
        Write-Warning "absent on this host, skipping: $($t.Path)"
        continue
    }
    $safe = ($t.Path -replace '[\\:]', '_')
    $bak = Join-Path $BackupDir "$safe.acl"
    if (-not (Test-Path $bak)) {
        & icacls $t.Path /save $bak | Out-Null
        Write-Host "backed up ACL: $($t.Path) -> $bak"
    }

    if ($t.Path -like 'HK*') {
        $key = [Microsoft.Win32.Registry]::LocalMachine.OpenSubKey(
            ($t.Path -replace '^HKLM\\', ''),
            [Microsoft.Win32.RegistryKeyPermissionCheck]::ReadWriteSubTree,
            [System.Security.AccessControl.RegistryRights]::ChangePermissions)
        $acl = $key.GetAccessControl()
        $rule = New-Object System.Security.AccessControl.RegistryAuditRule(
            $principal, $rights, $inheritance, $propagation, $auditType)
        $acl.AddAuditRule($rule)
        $key.SetAccessControl($acl)
        $key.Close()
        Write-Host "audit ACE added: $($t.Path) - $($t.Why)"
    } else {
        $acl = Get-Acl -Path $t.Path
        $rule = New-Object System.Security.AccessControl.FileSystemAuditRule(
            $principal,
            [System.Security.AccessControl.FileSystemRights]::ReadData,
            $inheritance, $propagation, $auditType)
        $acl.AddAuditRule($rule)
        Set-Acl -Path $t.Path -AclObject $acl
        Write-Host "audit ACE added: $($t.Path) - $($t.Why)"
    }
}

Write-Host ""
Write-Host "Applied. Now capture 24 hours of clean baseline before enabling the"
Write-Host "rules that read 4663, or the volume will bury the signal."
Write-Host "Rollback: .\set-sacls.ps1 -Rollback"

# Prove the SACL is live. A SACL that reads back empty is the failure this
# script exists to prevent, and it looks exactly like a quiet rule.
foreach ($t in $targets) {
    if ($t.Path -like 'HK*') {
        $key = [Microsoft.Win32.Registry]::LocalMachine.OpenSubKey(
            ($t.Path -replace '^HKLM\\', ''))
        $has = ($key.GetAccessControl().GetAuditRules(
            $true, $true, [System.Security.Principal.NTAccount]) | Measure-Object).Count
        $key.Close()
    } else {
        $has = (Get-Acl -Path $t.Path -Audit).Audit.Count
    }
    if ($has -lt 1) {
        Write-Error "SACL read back empty for $($t.Path) - the rule that reads it cannot fire"
    }
}
Write-Host "verified: every target reports at least one audit ACE."
